// Unit converter helper for raw file headers
if (!function_exists('parse_unit_val')) {
	function parse_unit_val($val, $unit) {
		$v = floatval($val);
		$u = strtolower(trim($unit));
		if ($u == 'nm') return $v * 1e-9;
		if ($u == 'pm') return $v * 1e-12;
		if ($u == 'um' || $u == 'µm') return $v * 1e-6;
		if ($u == 'å' || $u == 'a') return $v * 1e-10;
		return $v;
	}
}

// Native PHP parser for SPM/STM/AFM file headers (.sxm, .top, .Z_out, .hdr, etc.) as backup
if (!function_exists('parse_spm_header')) {
	function parse_spm_header($filepath) {
		$res = array('xo' => 0.0, 'yo' => 0.0, 'xs' => 50e-9, 'ys' => 50e-9, 'ang' => 0.0, 'time' => '');
		$base_path = preg_replace('/\.(f|b)\d+$/i', '', $filepath);
		
		$hdr = @file_get_contents($base_path, false, null, 0, 8192);
	if (!$hdr) $hdr = @file_get_contents($filepath, false, null, 0, 8192);
	if (!$hdr) return $res;

	// Nanonis .sxm format
	if (preg_match('/:SCAN_OFFSET:\s*([\d\.\-E\+]+)\s+([\d\.\-E\+]+)/i', $hdr, $m)) {
		$res['xo'] = floatval($m[1]);
		$res['yo'] = floatval($m[2]);
	}
	if (preg_match('/:SCAN_RANGE:\s*([\d\.\-E\+]+)\s+([\d\.\-E\+]+)/i', $hdr, $m)) {
		$res['xs'] = floatval($m[1]);
		$res['ys'] = floatval($m[2]);
	}
	if (preg_match('/:SCAN_ANGLE:\s*([\d\.\-E\+]+)/i', $hdr, $m)) {
		$res['ang'] = floatval($m[1]);
	}
	if (preg_match('/:REC_DATE:\s*([^\r\n]+)/i', $hdr, $m_d) && preg_match('/:REC_TIME:\s*([^\r\n]+)/i', $hdr, $m_t)) {
		$res['time'] = trim($m_d[1]) . ' ' . trim($m_t[1]);
	}

	// WSxM format
	if (preg_match('/X Offset:\s*([\d\.\-E\+]+)\s*([a-zµÅ]+)?/i', $hdr, $m)) {
		$res['xo'] = parse_unit_val($m[1], isset($m[2]) ? $m[2] : 'm');
	}
	if (preg_match('/Y Offset:\s*([\d\.\-E\+]+)\s*([a-zµÅ]+)?/i', $hdr, $m)) {
		$res['yo'] = parse_unit_val($m[1], isset($m[2]) ? $m[2] : 'm');
	}
	if (preg_match('/X Amplitude:\s*([\d\.\-E\+]+)\s*([a-zµÅ]+)?/i', $hdr, $m)) {
		$res['xs'] = parse_unit_val($m[1], isset($m[2]) ? $m[2] : 'm');
	}
	if (preg_match('/Y Amplitude:\s*([\d\.\-E\+]+)\s*([a-zµÅ]+)?/i', $hdr, $m)) {
		$res['ys'] = parse_unit_val($m[1], isset($m[2]) ? $m[2] : 'm');
	}
	if (preg_match('/Angle:\s*([\d\.\-E\+]+)/i', $hdr, $m)) {
		$res['ang'] = floatval($m[1]);
	}
	if (preg_match('/Acquisition time:\s*([^\r\n]+)/i', $hdr, $m)) {
		$res['time'] = trim($m[1]);
	}

	if ($res['xs'] <= 0) $res['xs'] = 50e-9;
	if ($res['ys'] <= 0) $res['ys'] = 50e-9;

	return $res;
	}
}

// 1. Primary Metadata Source: Read imgoffs.dat generated by qvud in GDL
$imgoffs_file = $userdir . $user . '/imgoffs.dat';
$qvud_meta = array();

if (file_exists($imgoffs_file)) {
	$lines = file($imgoffs_file);
	for ($i = 0; $i < count($lines); $i++) {
		$l1 = trim($lines[$i]);
		if (empty($l1)) continue;
		$p1 = explode(';', $l1);

		// Single-line format (9 fields)
		if (count($p1) >= 8 && is_numeric(trim($p1[0]))) {
			$c_idx = intval($p1[0]);
			$xo_v = floatval($p1[3]);
			$yo_v = floatval($p1[4]);
			$xs_v = floatval($p1[5]);
			$ys_v = floatval($p1[6]);
			if (abs($xo_v) > 1e-3) $xo_v *= 1e-9;
			if (abs($yo_v) > 1e-3) $yo_v *= 1e-9;
			if ($xs_v > 1e-3) $xs_v *= 1e-9;
			if ($ys_v > 1e-3) $ys_v *= 1e-9;
			$qvud_meta[$c_idx] = array(
				'xo' => $xo_v,
				'yo' => $yo_v,
				'xs' => $xs_v > 0 ? $xs_v : 50e-9,
				'ys' => $ys_v > 0 ? $ys_v : 50e-9,
				'ang' => floatval($p1[7]),
				'time' => isset($p1[8]) ? trim($p1[8]) : ''
			);
			continue;
		}

		// 2-line qvud imgoffs format
		if (isset($lines[$i + 1])) {
			$l2 = trim($lines[$i + 1]);
			$p2 = explode(';', $l2);
			if (count($p1) >= 8 && count($p2) >= 5) {
				$c_idx = intval(trim($p1[0]));
				$xo = floatval(trim($p1[7]));
				$yo = isset($p1[9]) ? floatval(trim($p1[9])) : 0.0;
				
				$xs_nm = floatval(trim($p2[1]));
				$ys_nm = floatval(trim($p2[4]));
				$xs = ($xs_nm > 0 ? $xs_nm : 50.0) * 1e-9;
				$ys = ($ys_nm > 0 ? $ys_nm : $xs_nm) * 1e-9;
				$ang = floatval(trim($p2[0]));

				$qvud_meta[$c_idx] = array(
					'xo' => $xo,
					'yo' => $yo,
					'xs' => $xs,
					'ys' => $ys,
					'ang' => $ang,
					'time' => ''
				);
				$i++; // skip next line
			}
		}
	}
}

