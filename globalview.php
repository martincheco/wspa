// Calculate physical centroid (unweighted mean position of unique image centers) and maximum corner extents under viewAngle
function getDatasetCentroidAndExtents() {
	var visibleItems = getVisibleItems();
	var uniqueScansMap = {};
	
	visibleItems.forEach(function(item) {
		if (!uniqueScansMap[item.file_idx]) {
			uniqueScansMap[item.file_idx] = item;
		}
	});

	var uniqueScans = [];
	for (var key in uniqueScansMap) {
		uniqueScans.push(uniqueScansMap[key]);
	}

	if (uniqueScans.length === 0) {
		return null;
	}

	// 1. Calculate Unweighted Centroid (unweighted mean physical position of unique scan centers)
	var sumX = 0, sumY = 0;
	uniqueScans.forEach(function(item) {
		sumX += item.xo;
		sumY += item.yo;
	});
	var meanX = sumX / uniqueScans.length;
	var meanY = sumY / uniqueScans.length;

	// 2. Calculate maximum X and Y offsets from centroid for all 4 corners of all unique visible items under viewAngle
	var radRot = -(viewAngle * Math.PI / 180.0);
	var maxDx = 0, maxDy = 0;

	uniqueScans.forEach(function(item) {
		var dx = item.xo - meanX;
		var dy = item.yo - meanY;
		var rotX = meanX + (dx * Math.cos(radRot) - dy * Math.sin(radRot));
		var rotY = meanY + (dx * Math.sin(radRot) + dy * Math.cos(radRot));

		var hw = item.xs / 2;
		var hh = item.ys / 2;
		var netAngle = item.ang - viewAngle;
		var rad = netAngle * Math.PI / 180.0;
		var corners = [
			{x: -hw, y: -hh},
			{x: hw, y: -hh},
			{x: hw, y: hh},
			{x: -hw, y: hh}
		];
		corners.forEach(function(pt) {
			var cornerPhysX = rotX + (pt.x * Math.cos(rad) - pt.y * Math.sin(rad));
			var cornerPhysY = rotY + (pt.x * Math.sin(rad) + pt.y * Math.cos(rad));

			var cDx = Math.abs(cornerPhysX - meanX);
			var cDy = Math.abs(cornerPhysY - meanY);

			if (cDx > maxDx) maxDx = cDx;
			if (cDy > maxDy) maxDy = cDy;
		});
	});

	if (maxDx <= 0) maxDx = 1e-7;
	if (maxDy <= 0) maxDy = 1e-7;

	return {
		meanX: meanX,
		meanY: meanY,
		maxDx: maxDx,
		maxDy: maxDy
	};
}

// Calculate dataset physical bounds for visible images inside time interval
function getBounds() {
	var meta = getDatasetCentroidAndExtents();
	if (!meta) {
		return {minX: -1e-7, maxX: 1e-7, minY: -1e-7, maxY: 1e-7, w: 2e-7, h: 2e-7, midX: 0, midY: 0};
	}
	return {
		minX: meta.meanX - meta.maxDx,
		maxX: meta.meanX + meta.maxDx,
		minY: meta.meanY - meta.maxDy,
		maxY: meta.meanY + meta.maxDy,
		w: meta.maxDx * 2,
		h: meta.maxDy * 2,
		midX: meta.meanX,
		midY: meta.meanY
	};
}

function getBaseZoomScale1x() {
	var cw = viewport ? viewport.clientWidth : 0;
	if (cw <= 0) cw = 1000;
	return cw / 100e-9;
}

function zoomScaleToCoeff(scale) {
	var base1x = getBaseZoomScale1x();
	return base1x > 0 ? scale / base1x : 1.0;
}

function coeffToZoomScale(coeff) {
	return coeff * getBaseZoomScale1x();
}

function updateMinZoomScale() {
	minZoomScale = coeffToZoomScale(0.001);
}

function getMaxZoomScale() {
	return coeffToZoomScale(1000.0);
}

function getFitScale() {
	var cw = viewport ? viewport.clientWidth : 0;
	var ch = viewport ? viewport.clientHeight : 0;
	if (cw <= 0 || ch <= 0) return getBaseZoomScale1x();
	var meta = getDatasetCentroidAndExtents();
	if (!meta) return getBaseZoomScale1x();
	var scaleX = (cw * 0.45) / meta.maxDx;
	var scaleY = (ch * 0.45) / meta.maxDy;
	return Math.min(scaleX, scaleY);
}

function updateZoomSliderReadout() {
	var slider = document.getElementById('gvZoomSlider');
	var readout = document.getElementById('gvZoomVal');
	if (!slider || !readout) return;

	var coeff = zoomScaleToCoeff(zoomScale);
	var text = '';
	if (coeff >= 10) {
		text = coeff.toFixed(1) + 'x';
	} else if (coeff >= 1) {
		text = coeff.toFixed(2) + 'x';
	} else if (coeff >= 0.1) {
		text = coeff.toFixed(2) + 'x';
	} else {
		text = coeff.toFixed(3) + 'x';
	}
	readout.textContent = text;

	var minCoeff = 0.01;
	var maxCoeff = 100.0;
	var minLog = Math.log(minCoeff);
	var maxLog = Math.log(maxCoeff);
	var curLog = Math.log(Math.max(minCoeff, Math.min(maxCoeff, coeff)));

	var t = (maxLog > minLog) ? (curLog - minLog) / (maxLog - minLog) : 0.5;
	t = Math.max(0, Math.min(1, t));
	slider.value = Math.round(1 + t * 99);
}

function onZoomSliderChange() {
	var slider = document.getElementById('gvZoomSlider');
	if (!slider) return;
	var val = parseInt(slider.value, 10);
	var t = (val - 1) / 99;

	var minCoeff = 0.01;
	var maxCoeff = 100.0;
	var minLog = Math.log(minCoeff);
	var maxLog = Math.log(maxCoeff);

	var targetCoeff = Math.exp(minLog + t * (maxLog - minLog));
	var targetScale = coeffToZoomScale(targetCoeff);
	var cw = viewport ? viewport.clientWidth : 0;
	var ch = viewport ? viewport.clientHeight : 0;
	applyZoom(targetScale, cw / 2, ch / 2);
}

function stepZoom(dir) {
