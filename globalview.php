// Helper to strip ONLY up/down scan direction differences
if (!function_exists('clean_channel_name')) {
	function clean_channel_name($raw) {
		$str = trim($raw);
		$str = preg_replace('/\s*\((up|down)\)/i', '', $str);
		$str = preg_replace('/\b(up|down)\b/i', '', $str);
		$str = preg_replace('/\s+/', ' ', $str);
		$str = trim($str);
		return !empty($str) ? $str : trim($raw);
	}
}

