// Keyboard Navigation & Shortcuts
window.addEventListener('keydown', function(e) {
	if (e.target.tagName === 'TEXTAREA' || (e.target.tagName === 'INPUT' && (e.target.type === 'text' || e.target.type === 'password'))) return;

	var isCtrl = e.ctrlKey || e.metaKey;

	if (isCtrl && (e.key === 'c' || e.key === 'C')) {
		var selectedText = window.getSelection ? window.getSelection().toString() : '';
		if (!selectedText && tooltip && tooltip.style.display !== 'none' && tooltip.innerText && tooltip.innerText.trim() !== '') {
			var textToCopy = tooltip.innerText;
			if (navigator.clipboard && navigator.clipboard.writeText) {
				navigator.clipboard.writeText(textToCopy).then(function() {
					flashTooltipCopyFeedback();
				}).catch(function() {
					fallbackCopyText(textToCopy);
				});
			} else {
				fallbackCopyText(textToCopy);
			}
		}
		return;
	}

	if (e.key === 'ArrowUp') {
		stepFocus(1);
		e.preventDefault();
	} else if (e.key === 'ArrowDown') {
		stepFocus(-1);
		e.preventDefault();
	} else if (e.key === 'ArrowLeft') {
		stepSelectDropdown(isCtrl ? 'gvSecChanFilter' : 'gvChanFilter', -1);
		e.preventDefault();
	} else if (e.key === 'ArrowRight') {
		stepSelectDropdown(isCtrl ? 'gvSecChanFilter' : 'gvChanFilter', 1);
		e.preventDefault();
	} else if (e.key === '=' || e.key === '+' || e.key === 'Add') {
		stepZoom(1);
		e.preventDefault();
	} else if (e.key === '-' || e.key === 'Subtract') {
		stepZoom(-1);
		e.preventDefault();
	} else if (e.key === 'w' || e.key === 'W') {
		stepPitch(1);
		e.preventDefault();
	} else if (e.key === 's' || e.key === 'S') {
		stepPitch(-1);
		e.preventDefault();
	} else if (e.key === 'a' || e.key === 'A' || e.key === 'q' || e.key === 'Q') {
		stepRot(-1);
		e.preventDefault();
	} else if (e.key === 'd' || e.key === 'D' || e.key === 'e' || e.key === 'E') {
		stepRot(1);
		e.preventDefault();
	} else if (e.key === 'z' || e.key === 'Z') {
		stepZSep(-1);
		e.preventDefault();
	} else if (e.key === 'x' || e.key === 'X') {
		stepZSep(1);
		e.preventDefault();
	} else if (e.key === '[') {
		stepAlpha(-1);
		e.preventDefault();
	} else if (e.key === ']') {
		stepAlpha(1);
		e.preventDefault();
	} else if (e.key === 'f' || e.key === 'F') {
		fitView();
		e.preventDefault();
	} else if (e.key === ' ' || e.code === 'Space') {
		centerFocusedImage();
		e.preventDefault();
	} else if (e.key === 'PageUp') {
		setFocusAsMaxRange();
		e.preventDefault();
	} else if (e.key === 'PageDown') {
		setFocusAsMinRange();
		e.preventDefault();
	} else if (e.key === 'Enter') {
		openFocusedImageInAnalysis();
		e.preventDefault();
	}
});

