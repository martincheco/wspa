// Wheel Navigation: Ctrl-Scroll for Upper Threshold, Left-Click+Scroll for Active Image Stepping, Wheel for Zoom
var lastWheelStepTime = 0;
var WHEEL_STEP_COOLDOWN = 70; // ms minimum delay between single-step wheel increments

window.addEventListener('wheel', function(e) {
	if (e.ctrlKey) {
		e.preventDefault();
		if (isLeftClickPanning) return; // Suppress threshold stepping during Ctrl+mouse drag pitch/yaw rotation
		var now = performance.now();
		if (now - lastWheelStepTime >= WHEEL_STEP_COOLDOWN) {
			lastWheelStepTime = now;
			var dir = e.deltaY < 0 ? 1 : -1;
			stepTime('max', dir);
		}
	}
}, { passive: false });

canvas.addEventListener('wheel', function(e) {
	var now = performance.now();

	if (isLeftClickPanning || (e.buttons & 1) === 1) {
		e.preventDefault();
		if (e.ctrlKey) {
			// Suppress wheel zoom/threshold stepping while dragging mouse with Ctrl key held for pitch/yaw
			return;
		}
		hasDraggedMouse = true;
		if (now - lastWheelStepTime >= WHEEL_STEP_COOLDOWN) {
			lastWheelStepTime = now;
			var dir = e.deltaY < 0 ? 1 : -1;
			var channelItems = getAllChannelItems();
			if (channelItems.length > 0) {
				var currentVisIdx = channelItems.findIndex(function(v) { return v.c === focusedIndex; });
				if (currentVisIdx < 0) {
					var focusItem = rawData.find(function(it) { return it.c === focusedIndex; });
					var targetIdx = focusItem ? focusItem.file_idx : activeFileIdx;
					var minDiff = Infinity;
					currentVisIdx = 0;
					channelItems.forEach(function(item, idx) {
						var diff = Math.abs(item.file_idx - targetIdx);
						if (diff < minDiff) {
							minDiff = diff;
							currentVisIdx = idx;
						}
					});
				}
				var nextVisIdx = currentVisIdx + dir;
				nextVisIdx = Math.max(0, Math.min(channelItems.length - 1, nextVisIdx));
				var targetItem = channelItems[nextVisIdx];
				if (targetItem) {
					centerImage(targetItem, true); // Preserve zoom scale
				}
			}
		}
		return;
	}

	if (e.ctrlKey) {
		e.preventDefault();
		if (now - lastWheelStepTime >= WHEEL_STEP_COOLDOWN) {
			lastWheelStepTime = now;
			var dir = e.deltaY < 0 ? 1 : -1;
			stepTime('max', dir);
		}
		return;
	}

	e.preventDefault();
	var rect = canvas.getBoundingClientRect();
	var mouseX = e.clientX - rect.left;
	var mouseY = e.clientY - rect.top;

	var zoomFactor = e.deltaY < 0 ? 1.15 : 0.85;
	var targetScale = zoomScale * zoomFactor;

	applyZoom(targetScale, mouseX, mouseY);
}, { passive: false });

function flashTooltipCopyFeedback() {
	if (!tooltip) return;
	var origBorder = tooltip.style.borderColor;
	tooltip.style.borderColor = '#0f0';
	tooltip.style.boxShadow = '0 0 10px #0f0';
	setTimeout(function() {
		tooltip.style.borderColor = origBorder || '#555';
		tooltip.style.boxShadow = 'none';
	}, 350);
}

function fallbackCopyText(text) {
	var textArea = document.createElement('textarea');
	textArea.value = text;
	textArea.style.position = 'fixed';
	textArea.style.left = '-9999px';
	textArea.style.top = '-9999px';
	document.body.appendChild(textArea);
	textArea.focus();
	textArea.select();
	try {
		document.execCommand('copy');
		flashTooltipCopyFeedback();
	} catch (err) {
		console.error('Fallback copy failed', err);
	}
	document.body.removeChild(textArea);
}

function stepSelectDropdown(selectId, dir) {
	var sel = document.getElementById(selectId);
	if (!sel || sel.options.length === 0) return;
	var idx = sel.selectedIndex + dir;
	while (idx >= 0 && idx < sel.options.length) {
		if (!sel.options[idx].disabled) {
			sel.selectedIndex = idx;
			if (typeof sel.onchange === 'function') {
				sel.onchange();
			} else {
				sel.dispatchEvent(new Event('change'));
			}
			break;
		}
		idx += dir;
	}
}

function stepAlpha(dir) {
	var input = document.getElementById('gvAlpha');
	if (!input) return;
	var val = parseInt(input.value, 10) + dir * 5;
	val = Math.max(10, Math.min(100, val));
	input.value = val;
	onAlphaChange();
}

