function onFilterChange() {
	syncChannelDropdowns();
	saveSpatialViewState();
	var qvudItem = rawData.find(function(item) { return item.c === qvudIndex; });
	var focusedItem = rawData.find(function(item) { return item.c === focusedIndex; });

	var targetQVUDFileIdx = qvudItem ? qvudItem.file_idx : activeFileIdx;
	var targetFocusFileIdx = focusedItem ? focusedItem.file_idx : targetQVUDFileIdx;

	var visibleItems = getVisibleItems();
	if (visibleItems.length > 0) {
		var qMatch = visibleItems.find(function(item) { return item.file_idx === targetQVUDFileIdx; });
		if (!qMatch) {
			var minDiff = Infinity;
			visibleItems.forEach(function(item) {
				var diff = Math.abs(item.file_idx - targetQVUDFileIdx);
				if (diff < minDiff) { minDiff = diff; qMatch = item; }
			});
		}
		if (qMatch) qvudIndex = qMatch.c;

		var fMatch = visibleItems.find(function(item) { return item.file_idx === targetFocusFileIdx; });
		if (!fMatch) {
			var minDiff = Infinity;
			visibleItems.forEach(function(item) {
				var diff = Math.abs(item.file_idx - targetFocusFileIdx);
				if (diff < minDiff) { minDiff = diff; fMatch = item; }
			});
		}
		if (fMatch) {
			focusedIndex = fMatch.c;
			activeIndex = fMatch.c;
		}
	}

	updateHeaderReadout();
	clampPan();
	requestDraw();
}

