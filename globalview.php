	}

	$current_file_idx = max(0, $file_idx);
	$actual_file_name = isset($mylist_names[$current_file_idx]) ? $mylist_names[$current_file_idx] : (preg_match('/tmp\d+\.png$/i', basename($raw_file)) ? $bi : basename($raw_file));

	$js_images[] = array(
		'c' => $c,
		'file_idx' => $current_file_idx,
		'file_num' => $current_file_idx + 1,
		'bi' => $bi,
		'file' => $actual_file_name,
		'chan' => $ch_name,
		'xo' => $meta['xo'],
		'yo' => $meta['yo'],
		'xs' => $meta['xs'],
		'ys' => $meta['ys'],
		'ang' => $meta['ang'],
		'time' => $meta['time'],
		'src' => $real_src,
		'bordercol' => $bordercol,
		'is_active' => in_array($c, $chline),
		'sts_points' => $sts_points
	);

