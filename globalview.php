function isPointInQuad(px, py, quad) {
	var p0 = quad[0], p1 = quad[1], p2 = quad[2], p3 = quad[3];
	var cp0 = (p1.x - p0.x) * (py - p0.y) - (p1.y - p0.y) * (px - p0.x);
	var cp1 = (p2.x - p1.x) * (py - p1.y) - (p2.y - p1.y) * (px - p1.x);
	var cp2 = (p3.x - p2.x) * (py - p2.y) - (p3.y - p2.y) * (px - p2.x);
	var cp3 = (p0.x - p3.x) * (py - p3.y) - (p0.y - p3.y) * (px - p3.x);
	var hasPos = (cp0 > 0) || (cp1 > 0) || (cp2 > 0) || (cp3 > 0);
	var hasNeg = (cp0 < 0) || (cp1 < 0) || (cp2 < 0) || (cp3 < 0);
	return !(hasPos && hasNeg);
}

function drawSegmentRun(points, isObs, solidColor, faintColor, dashUnobs) {
	ctx.save();
	ctx.lineWidth = 2.0;
	if (isObs) {
		ctx.strokeStyle = faintColor;
		ctx.setLineDash([4, 4]);
	} else {
		ctx.strokeStyle = solidColor;
		ctx.setLineDash(dashUnobs ? [4, 4] : []);
	}
	ctx.beginPath();
	ctx.moveTo(points[0].x, points[0].y);
	for (var j = 1; j < points.length; j++) {
		ctx.lineTo(points[j].x, points[j].y);
	}
	ctx.stroke();
	ctx.restore();
}

function drawObscurableEdge(ptA, ptB, targetVisIdx, higherItems, solidColor, faintColor, numSamples, dashUnobs) {
	if (!numSamples) numSamples = 12;

	if (!higherItems || higherItems.length === 0) {
		ctx.save();
		ctx.lineWidth = 2.0;
		ctx.strokeStyle = solidColor;
		ctx.setLineDash(dashUnobs ? [4, 4] : []);
		ctx.beginPath();
		ctx.moveTo(ptA.x, ptA.y);
		ctx.lineTo(ptB.x, ptB.y);
		ctx.stroke();
		ctx.restore();
		return;
	}

	var samples = [];
	for (var i = 0; i <= numSamples; i++) {
		var t = i / numSamples;
		var sx = ptA.x + t * (ptB.x - ptA.x);
		var sy = ptA.y + t * (ptB.y - ptA.y);
		var obs = false;
		for (var k = 0; k < higherItems.length; k++) {
			if (isPointInQuad(sx, sy, higherItems[k].quad)) {
				obs = true;
				break;
			}
		}
		samples.push({ x: sx, y: sy, obscured: obs });
	}

	var currentObs = samples[0].obscured || samples[1].obscured;
	var runPoints = [samples[0]];

	for (var i = 0; i < numSamples; i++) {
		var pEnd = samples[i + 1];
		var isObs = samples[i].obscured || pEnd.obscured;

		if (isObs !== currentObs) {
			drawSegmentRun(runPoints, currentObs, solidColor, faintColor, dashUnobs);
			currentObs = isObs;
			runPoints = [samples[i]];
		}
		runPoints.push(pEnd);
	}
	if (runPoints.length > 1) {
		drawSegmentRun(runPoints, currentObs, solidColor, faintColor, dashUnobs);
	}
}

function drawObscurableFrame(quad, targetVisIdx, itemsWith3D, solidColor, faintColor, insetPx) {
	var higherItems = itemsWith3D.filter(function(e) { return e.visIdx > targetVisIdx; });
	var q = quad;
	if (insetPx && insetPx !== 0) {
		var cx = (quad[0].x + quad[1].x + quad[2].x + quad[3].x) / 4;
		var cy = (quad[0].y + quad[1].y + quad[2].y + quad[3].y) / 4;
		q = quad.map(function(pt) {
			var dx = cx - pt.x;
			var dy = cy - pt.y;
			var len = Math.hypot(dx, dy);
			if (len <= 0) return { x: pt.x, y: pt.y };
			return {
				x: pt.x + (dx / len) * insetPx,
				y: pt.y + (dy / len) * insetPx
			};
		});
	}

	drawObscurableEdge(q[0], q[1], targetVisIdx, higherItems, solidColor, faintColor);
	drawObscurableEdge(q[1], q[2], targetVisIdx, higherItems, solidColor, faintColor);
	drawObscurableEdge(q[2], q[3], targetVisIdx, higherItems, solidColor, faintColor);
	drawObscurableEdge(q[3], q[0], targetVisIdx, higherItems, solidColor, faintColor);
}

