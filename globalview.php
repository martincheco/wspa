// 3D Point Projection: maps physical ground point (x, y) at height zMeters to 2D screen coordinate (sx, sy)
function project3DPoint(x, y, zMeters) {
	if (!is3DMode) {
		var pivot = getPivot();
		var dx = x - pivot.x;
		var dy = y - pivot.y;
		var radRot = -(viewAngle * Math.PI / 180.0);
		var rotX = pivot.x + (dx * Math.cos(radRot) - dy * Math.sin(radRot));
		var rotY = pivot.y + (dx * Math.sin(radRot) + dy * Math.cos(radRot));
		var center = physToScreen(rotX, rotY);
		return { x: center.x, y: center.y, depth: 0 };
	}

	var dx = x - cachedFoc.x;
	var dy = y - cachedFoc.y;
	var dz = zMeters - cachedFoc.z;

	var rotX = dx * cachedTrig.cosYaw - dy * cachedTrig.sinYaw;
	var rotY = dx * cachedTrig.sinYaw + dy * cachedTrig.cosYaw;

	var sx = panX + rotX * zoomScale;
	var sy = panY - (rotY * cachedTrig.sinPitch + dz * cachedTrig.cosPitch) * zoomScale;

	var depth = dz * cachedTrig.sinPitch + rotY * cachedTrig.cosPitch;

	return { x: sx, y: sy, depth: depth };
}

// Get 4 projected 3D screen corners of an image item
function get3DQuadCorners(item, visIdx) {
	if (typeof visIdx === 'undefined') {
		var visibleItems = getVisibleItems();
		visIdx = visibleItems.findIndex(function(v) { return v.c === item.c; });
		if (visIdx < 0) visIdx = 0;
	}
	var zMeters = visIdx * getZStepMeters();
	var hw = item.xs / 2;
	var hh = item.ys / 2;
	var rad = -(item.ang * Math.PI / 180.0);

	var localCorners = [
		{ x: -hw, y: -hh }, // 0: Top-Left of PNG maps to Physical Bottom-Left
		{ x:  hw, y: -hh }, // 1: Top-Right of PNG maps to Physical Bottom-Right
		{ x:  hw, y:  hh }, // 2: Bottom-Right of PNG maps to Physical Top-Right
		{ x: -hw, y:  hh }  // 3: Bottom-Left of PNG maps to Physical Top-Left
	];

	return localCorners.map(function(pt) {
		var gx = item.xo + (pt.x * Math.cos(rad) - pt.y * Math.sin(rad));
		var gy = item.yo + (pt.x * Math.sin(rad) + pt.y * Math.cos(rad));
		return project3DPoint(gx, gy, zMeters);
	});
}

function get3DQuadCornersAtZ(item, visIdx, targetVisIdx) {
	if (typeof targetVisIdx === 'undefined') targetVisIdx = visIdx;
	var zMeters = targetVisIdx * getZStepMeters();
	var hw = item.xs / 2;
	var hh = item.ys / 2;
	var rad = -(item.ang * Math.PI / 180.0);

	var localCorners = [
		{ x: -hw, y: -hh },
		{ x:  hw, y: -hh },
		{ x:  hw, y:  hh },
		{ x: -hw, y:  hh }
	];

	return localCorners.map(function(pt) {
		var gx = item.xo + (pt.x * Math.cos(rad) - pt.y * Math.sin(rad));
		var gy = item.yo + (pt.x * Math.sin(rad) + pt.y * Math.cos(rad));
		return project3DPoint(gx, gy, zMeters);
	});
}

function isPointInQuad(px, py, quad) {
	var hasPos = false, hasNeg = false;
	for (var i = 0; i < 4; i++) {
		var pA = quad[i];
		var pB = quad[(i + 1) % 4];
		var cp = (pB.x - pA.x) * (py - pA.y) - (pB.y - pA.y) * (px - pA.x);
		if (cp > 1e-7) hasPos = true;
		if (cp < -1e-7) hasNeg = true;
		if (hasPos && hasNeg) return false;
	}
	return true;
}

// Aggregate multiple STS file names into bracketed range format (e.g. AALS-PL-hanging4000[02-23].dat)
function aggregateSTSNames(names, returnArray) {
	if (!names || names.length === 0) return returnArray ? [] : '';

	var uniqueNames = [];
	names.forEach(function(n) {
		if (n && uniqueNames.indexOf(n) === -1) {
			uniqueNames.push(n);
		}
	});

	if (uniqueNames.length === 1) {
		return returnArray ? uniqueNames : uniqueNames[0];
	}

	var groups = {};
	var nonMatching = [];

	uniqueNames.forEach(function(name) {
		var m = name.match(/^(.*?)(\d+)(\.[^.]+)?$/);
		if (m) {
			var prefix = m[1];
			var ext = m[3] || '';
			var key = prefix + '|||' + ext;
			if (!groups[key]) {
				groups[key] = { prefix: prefix, ext: ext, rawNames: [] };
			}
			groups[key].rawNames.push(name);
		} else {
			nonMatching.push(name);
		}
	});

	function getLCP(strs) {
		if (!strs || strs.length === 0) return '';
		var pref = strs[0];
		for (var i = 1; i < strs.length; i++) {
			while (strs[i].indexOf(pref) !== 0) {
				pref = pref.substring(0, pref.length - 1);
				if (pref === '') return '';
			}
		}
		return pref;
	}

	var formattedParts = [];

	for (var key in groups) {
		var g = groups[key];
		var rawList = g.rawNames;

		if (rawList.length === 1) {
			formattedParts.push(rawList[0]);
			continue;
		}

		var namesNoExt = rawList.map(function(n) {
			return g.ext ? n.substring(0, n.length - g.ext.length) : n;
		});

		var lcp = getLCP(namesNoExt);

		var items = namesNoExt.map(function(noExt, idx) {
			var suf = noExt.substring(lcp.length);
			var num = parseInt(suf, 10);
			return {
				fullName: rawList[idx],
				suf: suf,
				num: isNaN(num) ? null : num
			};
		});

		var allNumeric = items.every(function(it) { return it.num !== null; });

		if (allNumeric) {
			items.sort(function(a, b) { return a.num - b.num; });

			var uniqueItems = [];
			items.forEach(function(it) {
				if (!uniqueItems.some(function(u) { return u.num === it.num; })) {
					uniqueItems.push(it);
				}
			});

			var ranges = [];
			var curStart = uniqueItems[0];
			var curPrev = uniqueItems[0];

			for (var i = 1; i < uniqueItems.length; i++) {
				var curr = uniqueItems[i];
				if (curr.num === curPrev.num + 1) {
					curPrev = curr;
				} else {
					ranges.push({ start: curStart, end: curPrev });
					curStart = curr;
					curPrev = curr;
				}
			}
			ranges.push({ start: curStart, end: curPrev });

			var rangeStrings = ranges.map(function(r) {
				if (r.start.num === r.end.num) {
					return r.start.suf;
				} else if (r.end.num === r.start.num + 1) {
					return r.start.suf + ',' + r.end.suf;
				} else {
					return r.start.suf + '-' + r.end.suf;
				}
			});

			formattedParts.push(lcp + '[' + rangeStrings.join(',') + ']' + g.ext);
		} else {
			var sufList = items.map(function(it) { return it.suf; });
			formattedParts.push(lcp + '[' + sufList.join(',') + ']' + g.ext);
		}
	}

	nonMatching.forEach(function(nm) {
		formattedParts.push(nm);
	});

	return returnArray ? formattedParts : formattedParts.join('; ');
}

function stopAnimation() {
	if (activeAnim !== null) {
		cancelAnimationFrame(activeAnim);
		activeAnim = null;
	}
}

function animateViewTo(targetPanX, targetPanY, targetZoomScale, targetViewAngle, targetPitch, duration) {
	stopAnimation();
	if (typeof targetPitch === 'undefined' || targetPitch === null) {
		targetPitch = pitch3D;
	}
	duration = duration || VIEW_ANIM_DURATION;

	var cw = viewport.clientWidth;
	var ch = viewport.clientHeight;
	if (cw <= 0 || ch <= 0) return;

	var startPanX = panX;
	var startPanY = panY;
	var startZoom = zoomScale;
	var startAngle = viewAngle;
	var startPitch = pitch3D;

	var startPivot = {
		x: (cw / 2 - startPanX) / (startZoom > 0 ? startZoom : 1e-6),
		y: (startPanY - ch / 2) / (startZoom > 0 ? startZoom : 1e-6)
	};
	var targetPivot = {
		x: (cw / 2 - targetPanX) / (targetZoomScale > 0 ? targetZoomScale : 1e-6),
		y: (targetPanY - ch / 2) / (targetZoomScale > 0 ? targetZoomScale : 1e-6)
	};

	var dAngle = targetViewAngle - startAngle;
	while (dAngle > 180) dAngle -= 360;
	while (dAngle < -180) dAngle += 360;

	var logStartZoom = Math.log(startZoom > 0 ? startZoom : 1e-6);
	var logTargetZoom = Math.log(targetZoomScale > 0 ? targetZoomScale : 1e-6);

	var startTime = performance.now();

	function easeOutCubic(t) {
		return 1 - Math.pow(1 - t, 3);
	}

	function step(now) {
		var elapsed = now - startTime;
		var progress = Math.min(1.0, elapsed / duration);
		var ease = easeOutCubic(progress);

		zoomScale = Math.exp(logStartZoom + (logTargetZoom - logStartZoom) * ease);

		var curPivotX = startPivot.x + (targetPivot.x - startPivot.x) * ease;
		var curPivotY = startPivot.y + (targetPivot.y - startPivot.y) * ease;
		panX = cw / 2 - curPivotX * zoomScale;
		panY = ch / 2 + curPivotY * zoomScale;

		var currentAngle = Math.round(startAngle + dAngle * ease);
		while (currentAngle > 180) currentAngle -= 360;
		while (currentAngle < -180) currentAngle += 360;
		viewAngle = currentAngle;

		var currentPitch = Math.round(startPitch + (targetPitch - startPitch) * ease);
		pitch3D = Math.max(10, Math.min(90, currentPitch));

		var rotInput = document.getElementById('gvRot');
		var rotVal = document.getElementById('gvRotVal');
		if (rotInput) rotInput.value = viewAngle;
		if (rotVal) rotVal.textContent = viewAngle + '°';

		var pInput = document.getElementById('gv3DPitch');
		var pVal = document.getElementById('gv3DPitchVal');
		if (pInput) pInput.value = pitch3D;
		if (pVal) pVal.textContent = pitch3D + '°';

		requestDraw();

		if (progress < 1.0) {
			activeAnim = requestAnimationFrame(step);
		} else {
			activeAnim = null;
			clampPan();
			saveSpatialViewState();
			requestDraw();
		}
	}

	activeAnim = requestAnimationFrame(step);
}

// Convert meters to formatted physical string (nm / µm / mm)
function formatDist(m) {
	var absM = Math.abs(m);
	if (absM === 0) return '0 nm';
	if (absM < 1e-6) return (m * 1e9).toFixed(1) + ' nm';
	if (absM < 1e-3) return (m * 1e6).toFixed(2) + ' µm';
	return (m * 1e3).toFixed(2) + ' mm';
}

// Get current physical coordinate corresponding to the center of the viewport
function getPivot() {
	var cw = viewport.clientWidth;
	var ch = viewport.clientHeight;
	return {
		x: (cw / 2 - panX) / zoomScale,
		y: (panY - ch / 2) / zoomScale
	};
}

// Pan viewport by screen pixel deltas (mouseDx, mouseDy) accounting for view angle rotation
function panScreen(mouseDx, mouseDy) {
	stopAnimation();
	if (is3DMode) {
		panX += mouseDx;
		panY += mouseDy;
	} else {
		var radRot = viewAngle * Math.PI / 180.0;
		var dPanX = mouseDx * Math.cos(radRot) + mouseDy * Math.sin(radRot);
		var dPanY = -mouseDx * Math.sin(radRot) + mouseDy * Math.cos(radRot);
		panX += dPanX;
		panY += dPanY;
		clampPan();
	}
	requestDraw();
}

function cleanChanName(ch) {
	if (!ch) return '';
	var str = ch.trim();
	str = str.replace(/\s*\((up|down)\)/ig, '');
	str = str.replace(/\b(up|down)\b/ig, '');
	str = str.replace(/\s+/g, ' ');
	return str.trim();
}

