function onTimeSliderChange() {
	fileMin = parseInt(timeMinInput.value, 10);
	fileMax = parseInt(timeMaxInput.value, 10);

	if (fileMin > fileMax) {
		if (document.activeElement === timeMinInput) {
			fileMax = fileMin;
			timeMaxInput.value = fileMax;
		} else {
			fileMin = fileMax;
			timeMinInput.value = fileMin;
		}
	}

	var minValSpan = document.getElementById('gvTimeMinVal');
	var maxValSpan = document.getElementById('gvTimeMaxVal');
	if (minValSpan) minValSpan.textContent = (fileMin + 1);
	if (maxValSpan) maxValSpan.textContent = (fileMax + 1);

	// Exclusion area coloring on range slider tracks
	var minPct = maxFileIdx > 0 ? (fileMin / maxFileIdx) * 100 : 0;
	var maxPct = maxFileIdx > 0 ? (fileMax / maxFileIdx) * 100 : 100;

	timeMinInput.style.background = 'linear-gradient(to right, #622 0%, #622 ' + minPct + '%, #333 ' + minPct + '%, #333 100%)';
	timeMaxInput.style.background = 'linear-gradient(to right, #333 0%, #333 ' + maxPct + '%, #622 ' + maxPct + '%, #622 100%)';

	// Clamp focusedIndex to visible items matching active channel filter and time range
	var visItems = getVisibleItems();
	if (visItems.length > 0) {
		var isFocusVisible = visItems.some(function(v) { return v.c === focusedIndex; });
		if (!isFocusVisible) {
			var focusItem = rawData.find(function(it) { return it.c === focusedIndex; });
			var targetFileIdx = focusItem ? focusItem.file_idx : fileMax;
			var newFocus = null;
			if (targetFileIdx > fileMax) {
				// Threshold decreased below focus: pick uppermost visible image (largest file_idx in visItems)
				newFocus = visItems.reduce(function(prev, curr) {
					return (curr.file_idx > prev.file_idx) ? curr : prev;
				}, visItems[0]);
			} else if (targetFileIdx < fileMin) {
				// Threshold increased above focus: pick bottommost visible image (smallest file_idx in visItems)
				newFocus = visItems.reduce(function(prev, curr) {
					return (curr.file_idx < prev.file_idx) ? curr : prev;
				}, visItems[0]);
			} else {
				// Focus item was hidden by channel filter: pick closest visible image by file_idx
				var minDiff = Infinity;
				visItems.forEach(function(item) {
					var diff = Math.abs(item.file_idx - targetFileIdx);
					if (diff < minDiff) { minDiff = diff; newFocus = item; }
				});
			}
			if (newFocus) {
				centerImage(newFocus, false);
			} else {
				updateHeaderReadout();
			}
		} else {
			updateHeaderReadout();
		}
	} else {
		updateHeaderReadout();
	}

	requestDraw();
}

