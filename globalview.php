	var pitchRad = pitch3D * Math.PI / 180.0;
	cachedTrig = {
		cosYaw: Math.cos(totalYawRad),
		sinYaw: Math.sin(totalYawRad),
		sinPitch: Math.sin(pitchRad),
		cosPitch: Math.cos(pitchRad)
	};
