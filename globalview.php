var flatCache = {};

function isImageFlat(img) {
	if (!img || !img.complete || img.naturalWidth === 0) return false;
	var key = img.src;
	if (flatCache[key] !== undefined) return flatCache[key];

	try {
		var canvas = document.createElement('canvas');
		canvas.width = 16;
		canvas.height = 16;
		var ctx = canvas.getContext('2d');
		ctx.drawImage(img, 0, 0, 16, 16);
		var data = ctx.getImageData(0, 0, 16, 16).data;

		var r0 = data[0], g0 = data[1], b0 = data[2];
		var isFlat = true;
		for (var i = 0; i < data.length; i += 4) {
			if (Math.abs(data[i] - r0) > 4 || Math.abs(data[i+1] - g0) > 4 || Math.abs(data[i+2] - b0) > 4) {
				isFlat = false;
				break;
			}
		}
		flatCache[key] = isFlat;
		return isFlat;
	} catch (e) {
		flatCache[key] = false;
		return false;
	}
}

